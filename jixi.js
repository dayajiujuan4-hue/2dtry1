function jxCreateGrid(w,h,base){

  return Array.from(
    {length:h},
    ()=>Array(w).fill(base)
  );

}


function jxFill(
  grid,
  x,y,
  w,h,
  tile
){

  for(let yy=y;yy<y+h;yy++){

    for(let xx=x;xx<x+w;xx++){

      if(
        yy>=0 &&
        xx>=0 &&
        yy<grid.length &&
        xx<grid[0].length
      ){
        grid[yy][xx]=tile;
      }

    }

  }

}


// ============================================================
// OBJECT HELPERS
// ============================================================

function jxBuilding(
  x,y,w,h,
  name,
  color,
  doorX,
  target=null,
  style="urban",
  type="urban"
){

  return {
    x,y,w,h,
    name,
    color,
    doorX,
    target,
    type,
    jixiStyle:style
  };

}


function jxStall(
  x,y,width,
  sign,
  type="food"
){

  return {
    x,y,width,
    sign,
    type,
    jixi:true
  };

}


function jxProp(
  type,
  x,y,
  extra={}
){

  return {
    type,
    x,y,
    ...extra
  };

}


